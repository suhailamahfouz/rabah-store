function product(
  sku: string,
  slug: string,
  categorySlug: string,
  name: { ar: string; en: string },
  description: { ar: string; en: string },
  shortDescription: { ar: string; en: string },
  price: number,
  originalPrice: number | undefined,
  rating: number,
  reviewCount: number,
  colors: string[],
  photoIds: string[],
  stock: number,
) {
  return {
    sku,
    slug,
    categorySlug,
    name,
    description,
    shortDescription,
    price: originalPrice ?? price,
    salePrice: originalPrice ? price : undefined,
    rating,
    reviewCount,
    variants: colors.map((hex, index) => ({
      color: {
        name: { ar: `لون ${index + 1}`, en: `Color ${index + 1}` },
        hex,
      },
      stock: colors.length
        ? Math.floor(stock / colors.length) + (index < stock % colors.length ? 1 : 0)
        : 0,
    })),
    images: photoIds.map((id) => ({ url: image(id), alt: name.en })),
    features: [],
    stock,
    isFeatured: true,
    isBestSeller: false,
  };
}

